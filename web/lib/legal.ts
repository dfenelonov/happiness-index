// Шаблоны юридических документов. Плейсхолдеры в квадратных скобках заполняются при показе
// (fillLegal): реквизиты и email — из .env, остальное — из config/app.yaml → legal. Тексты стоит
// согласовать с юристом (LAUNCH.md → «Юридические тексты»). Это не юридическая консультация.

import { appConfig } from "./config";
import { seller, sellerLine } from "./seller";
import { support } from "./support";

export type LegalDoc = { title: string; sections: { h: string; p: string[] }[] };

const OPERATOR = "[реквизиты], email: [email для обращений]";

/** Подставить известные значения; незаполненные плейсхолдеры остаются в скобках. */
export function fillLegal(text: string, values: Record<string, string | null | undefined>): string {
  return text.replace(/\[([^\]]+)\]/g, (m, key: string) => values[key] || m);
}

/** Значения плейсхолдеров из .env и config/app.yaml. */
export function legalValues(env: Record<string, string | undefined> = process.env): Record<string, string | null> {
  const app = appConfig();
  let domain: string | null = null;
  try {
    domain = env.APP_URL ? new URL(env.APP_URL).host : null;
  } catch {
    domain = null;
  }
  return {
    реквизиты: sellerLine(seller(env)),
    "email для обращений": support(env).email,
    домен: domain,
    "срок возврата": String(app.pricing.refund_days),
    "дата публикации": app.legal.published_at,
    "наименование платёжного провайдера": app.legal.payment_provider,
    "наименование хостинга": app.legal.hosting,
    "наименование LLM-провайдера": app.legal.llm_provider,
    "срок хранения": app.legal.retention,
    "срок удаления": String(app.legal.deletion_days),
  };
}

/** Остались ли в документе незаполненные плейсхолдеры (тогда на странице плашка «Шаблон»). */
export const hasPlaceholders = (doc: LegalDoc, values: Record<string, string | null | undefined>) =>
  doc.sections.some((s) => s.p.some((p) => /\[[^\]]+\]/.test(fillLegal(p, values))));

